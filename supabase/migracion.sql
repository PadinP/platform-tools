CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS public.agentes_scraper (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    nombre text NOT NULL,
    token_hash text NOT NULL UNIQUE,
    activo boolean NOT NULL DEFAULT true,
    creado_en timestamptz NOT NULL DEFAULT now(),
    ultima_vez timestamptz
);

CREATE TABLE IF NOT EXISTS public.codigos_agente (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_hash text NOT NULL UNIQUE,
    creado_en timestamptz NOT NULL DEFAULT now(),
    vence_en timestamptz NOT NULL,
    usado_en timestamptz
);

ALTER TABLE public.solicitudes_scraper
    ADD COLUMN IF NOT EXISTS agente_id uuid REFERENCES public.agentes_scraper(id),
    ADD COLUMN IF NOT EXISTS archivo text;

CREATE INDEX IF NOT EXISTS ix_solicitudes_scraper_agente_pendiente
    ON public.solicitudes_scraper (agente_id, creado_en)
    WHERE estado = 'pendiente';

-- Evita dos ejecuciones simultáneas del mismo agente, también si alguien
-- pulsa dos veces el botón de Streamlit casi a la vez.
CREATE UNIQUE INDEX IF NOT EXISTS uq_solicitud_activa_por_agente
    ON public.solicitudes_scraper (agente_id)
    WHERE agente_id IS NOT NULL AND estado IN ('pendiente', 'ejecutando');

CREATE OR REPLACE FUNCTION public.reclamar_solicitud_agente(p_agente_id uuid)
RETURNS TABLE (id uuid)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    RETURN QUERY
    WITH siguiente AS (
        SELECT s.id
        FROM public.solicitudes_scraper AS s
        WHERE s.agente_id = p_agente_id AND s.estado = 'pendiente'
        ORDER BY s.creado_en ASC
        FOR UPDATE SKIP LOCKED
        LIMIT 1
    ), actualizado AS (
        UPDATE public.solicitudes_scraper AS s
        SET estado = 'ejecutando',
            iniciado_en = now(),
            mensaje = 'Agente de Windows ha iniciado el scraper'
        FROM siguiente
        WHERE s.id = siguiente.id AND s.estado = 'pendiente'
        RETURNING s.id
    )
    SELECT actualizado.id FROM actualizado;
END;
$$;

REVOKE ALL ON FUNCTION public.reclamar_solicitud_agente(uuid) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.reclamar_solicitud_agente(uuid) FROM anon, authenticated;
GRANT EXECUTE ON FUNCTION public.reclamar_solicitud_agente(uuid) TO service_role;

ALTER TABLE public.solicitudes_scraper ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.agentes_scraper ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.codigos_agente ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.agentes_scraper, public.codigos_agente FROM anon, authenticated;
-- solicitudes_scraper ya no se usa directamente por el agente; Streamlit
-- y la Edge Function acceden con clave secreta del servidor.
REVOKE ALL ON TABLE public.solicitudes_scraper FROM anon, authenticated;

